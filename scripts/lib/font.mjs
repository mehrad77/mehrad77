/** accented capitals: a base letter and the two rows over its cap line */
const MARKS = {
  "É": { base: "E", mark: ["...#.", "..#.."] },
};

export const MARK_ROWS = 2;
export const CAP = 7;
export const DESC = 2;
export const HEIGHT = MARK_ROWS + CAP + DESC;

// the font checks itself: every glyph 9 rows, every row as wide as its glyph, only "#" and "."
for (const [ch, rows] of Object.entries(GLYPHS)) {
  if (rows.length !== CAP + DESC) throw new Error(`glyph ${ch}: ${rows.length} rows`);
  if (rows.some((r) => r.length !== rows[0].length || /[^#.]/.test(r))) throw new Error(`glyph ${ch}: ragged or bad cells`);
}
for (const [ch, { base, mark }] of Object.entries(MARKS))
  if (!GLYPHS[base] || mark.some((r) => r.length !== GLYPHS[base][0].length)) throw new Error(`glyph ${ch}: bad mark`);

/** the glyph's 11 rows (2 mark rows, 7 cap rows, 2 descender rows), or null when the font lacks it */
function glyph(ch) {
  if (MARKS[ch]) return [...MARKS[ch].mark, ...GLYPHS[MARKS[ch].base]];
  const rows = GLYPHS[ch];
  return rows ? [...Array(MARK_ROWS).fill(".".repeat(rows[0].length)), ...rows] : null;
}

export const hasGlyph = (ch) => Boolean(glyph(ch));

/** Lay out a line: 11 rows of "#" and ".", glyphs 1 cell apart. Throws on a character the font lacks. */
export function proseRows(text) {
  const glyphs = [...text].map((ch) => {
    const rows = glyph(ch);
    if (!rows) throw new Error(`the 5x7 font has no glyph for ${JSON.stringify(ch)}`);
    return rows;
  });
  return Array.from({ length: HEIGHT }, (_, r) => glyphs.map((gl) => gl[r]).join("."));
}

export const proseWidth = (text) => proseRows(text)[0].length;

/** where each character starts, in cells: for underlining part of a line */
export function proseSpan(text, from, to) {
  const x = (n) => (n === 0 ? 0 : proseWidth(text.slice(0, n)) + 1);
  return [x(from), proseWidth(text.slice(0, to))];
}
