/**
 * A proportional 5x7 pixel font with lowercase, for the prose lines (the 3x5 HUD font in text.mjs stays the labels'
 * voice, as mono labels sit beside the serif on shab.boo). "#" is ink.
 *
 * Each glyph is 7 rows from the cap line down to the baseline, plus 2 descender rows; capitals and ascenders use all
 * 7, the x-height is the lower 5. An accented capital names its base letter and the 2 rows drawn above the cap line.
 * Glyphs sit 1 cell apart; a space is 3 cells.
 */

const BLANK_DESC = ["", ""];
const g = (rows, desc = BLANK_DESC) => {
  const w = Math.max(...rows.map((r) => r.length));
  return [...rows, ...desc.map((r) => r.padEnd(w, "."))].map((r) => r.padEnd(w, "."));
};

