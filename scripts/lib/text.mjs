/** Lay out text, glyphs `gap` cells apart (1, or 2 for a tracked label): five rows of "#" and ".". Throws on a
 * character the font lacks, so a label never ships with a hole in it. */
export function textRows(text, gap = 1) {
  const glyphs = [...text.toUpperCase()].map((ch) => {
    if (!FONT[ch]) throw new Error(`the 3x5 font has no glyph for ${JSON.stringify(ch)}`);
    return FONT[ch];
  });
  return [0, 1, 2, 3, 4].map((r) => glyphs.map((g) => g[r]).join(".".repeat(gap)));
}

export const textWidth = (text, gap = 1) => textRows(text, gap)[0].length;
